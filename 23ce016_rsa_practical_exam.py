# 2 & 3. FGSM and PGD Attacks Implementation

def fgsm_attack(image, epsilon, data_grad):
    sign_data_grad = data_grad.sign()
    perturbed_image = image + epsilon * sign_data_grad
    perturbed_image = torch.clamp(perturbed_image, 0, 1)
    return perturbed_image

def pgd_attack(model, images, labels, epsilon, alpha=None, iters=10):
    if epsilon == 0:
        return images
    if alpha is None:
        alpha = epsilon / 4

    # Random start within epsilon ball
    perturbed_images = images.clone().detach() + torch.FloatTensor(*images.shape).uniform_(-epsilon, epsilon).to(device)
    perturbed_images = torch.clamp(perturbed_images, 0, 1).detach()

    for i in range(iters):
        perturbed_images.requires_grad = True
        outputs = model(perturbed_images)
        loss = criterion(outputs, labels)
        model.zero_grad()
        loss.backward()

        # Gradient step
        adv_images = perturbed_images + alpha * perturbed_images.grad.sign()
        # Projection
        eta = torch.clamp(adv_images - images, min=-epsilon, max=epsilon)
        perturbed_images = torch.clamp(images + eta, min=0, max=1).detach()

    return perturbed_images

# Evaluation Loop optimized with a subset of 1000 images for fast CPU execution
def evaluate_robustness(model, dataloader, epsilons, max_samples=1000):
    model.eval()
    fgsm_accs = []
    pgd_accs = []

    for eps in epsilons:
        fgsm_correct = 0
        pgd_correct = 0
        total = 0

        for images, labels in dataloader:
            images, labels = images.to(device), labels.to(device)
            images.requires_grad = True

            # FGSM
            outputs = model(images)
            loss = criterion(outputs, labels)
            model.zero_grad()
            loss.backward()
            data_grad = images.grad.data

            perturbed_images_fgsm = fgsm_attack(images, eps, data_grad)
            outputs_fgsm = model(perturbed_images_fgsm)
            fgsm_correct += (outputs_fgsm.max(1)[1] == labels).sum().item()

            # PGD
            perturbed_images_pgd = pgd_attack(model, images, labels, eps)
            outputs_pgd = model(perturbed_images_pgd)
            pgd_correct += (outputs_pgd.max(1)[1] == labels).sum().item()

            total += labels.size(0)
            if total >= max_samples:
                break

        fgsm_accs.append(fgsm_correct / total * 100)
        pgd_accs.append(pgd_correct / total * 100)

    return fgsm_accs, pgd_accs

